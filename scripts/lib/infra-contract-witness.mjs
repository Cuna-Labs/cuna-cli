import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const IDENTITY_FILE = path.join("contracts", "infra", "cuna-api.openapi.identity.json");
const ARTIFACT_FILE = path.join("contracts", "infra", "cuna-api.openapi.json");
const WITNESS_SOURCE_FILE = path.join("src", "config", "infra-contract-witness.ts");
const HTTP_METHODS = Object.freeze(["get", "put", "post", "delete", "options", "head", "patch", "trace"]);

/**
 * Every operation the vendored contract declares, as `METHOD /path/template`,
 * sorted. This is what the CLI may say it serves: help and the command
 * preflight read it, so a routed command whose operation the contract lacks is
 * neither advertised as available nor sent.
 */
export function vendoredContractOperations(contractText) {
  let contract;
  try {
    contract = JSON.parse(contractText);
  } catch {
    throw new Error("Vendored Infra OpenAPI artifact is not JSON.");
  }
  const paths = contract?.paths;
  if (paths === null || typeof paths !== "object" || Array.isArray(paths)) {
    throw new Error("Vendored Infra OpenAPI artifact has no paths.");
  }
  const operations = [];
  for (const [template, row] of Object.entries(paths)) {
    for (const method of Object.keys(row ?? {})) {
      if (HTTP_METHODS.includes(method)) operations.push(`${method.toUpperCase()} ${template}`);
    }
  }
  return operations.sort();
}

/**
 * Keep the runtime gate's immutable producer evidence as compiled source. The
 * npm artifact does not ship the private control-plane contract directory, so
 * a filesystem lookup at command time would be an unverified local override.
 */
export function renderInfraContractWitness(identity, operations) {
  return "// Generated by scripts/sync-infra-openapi.mjs; do not edit manually.\n" +
    `export const INFRA_OPENAPI_CONTRACT_IDENTITY = Object.freeze(${JSON.stringify(identity, null, 2)} as const);\n` +
    `export const INFRA_OPENAPI_OPERATIONS: readonly string[] = Object.freeze(${JSON.stringify(operations, null, 2)});\n`;
}

export async function writeInfraContractWitness(root, identity) {
  const destination = path.join(root, WITNESS_SOURCE_FILE);
  const operations = vendoredContractOperations(await readFile(path.join(root, ARTIFACT_FILE), "utf8"));
  const rendered = renderInfraContractWitness(identity, operations);
  // A build should make the compiled witness follow the vendored contract, but
  // must not perturb a clean tree merely because it re-ran.  This also keeps
  // the source itself part of the exact release-input digest rather than an
  // incidental timestamped side effect of packaging.
  try {
    if (await readFile(destination, "utf8") === rendered) return;
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  await writeFile(destination, rendered, "utf8");
}

export async function emitVendoredInfraContractWitness(root) {
  const text = await readFile(path.join(root, IDENTITY_FILE), "utf8");
  let identity;
  try {
    identity = JSON.parse(text);
  } catch {
    throw new Error("Vendored Infra OpenAPI identity is not JSON.");
  }
  await writeInfraContractWitness(root, identity);
}

export const INFRA_CONTRACT_IDENTITY_FILE = IDENTITY_FILE;
export const INFRA_CONTRACT_WITNESS_SOURCE_FILE = WITNESS_SOURCE_FILE;
