import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const bytes=readFileSync(new URL('../contracts/infra/cuna-api.openapi.json',import.meta.url));
const spec=JSON.parse(bytes);
const names=['ProviderProfileCatalogResponseV2','ProviderObservationResponseV2','ProviderSessionCreateRequestV2'];
const schemas=Object.fromEntries(names.map(name=>[name,spec.components.schemas[name]]));
schemas.ProviderSessionSelectionV2=spec.components.schemas.ProviderSessionCreateResponseV2.properties.selection;
schemas.Uuid=spec.components.schemas.Uuid;
const operations=Object.fromEntries(['providerProfiles.catalogV2','agentSessions.createProviderSessionV2','agentSessions.providerObservationV2'].map(id=>{
 const matches=Object.entries(spec.paths).flatMap(([path,item])=>Object.entries(item).filter(([,op])=>op.operationId===id).map(([method])=>({path,method:method.toUpperCase()})));
 if(matches.length!==1||matches[0].method!=='POST')throw Error('V2 operation drift');
 return [id,matches[0]];
}));
const output=`/* oxlint-disable unicorn/no-thenable -- JSON Schema conditional keyword */
// Generated by scripts/project-provider-v2.mjs; source SHA256 ${createHash('sha256').update(bytes).digest('hex')}\nexport const providerV2Schemas = ${JSON.stringify(schemas,null,2)} as const;\nexport const providerV2Operations = ${JSON.stringify(operations,null,2)} as const;\n`;
const target=new URL('../src/api/provider-v2-schema.ts',import.meta.url);
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==output)throw Error('V2 projection drift');}else writeFileSync(target,output);
